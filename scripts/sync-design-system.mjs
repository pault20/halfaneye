// Copies the approved design system from docs/brief/design-system into src/styles.
// - tokens.css: copied as-is, plus an automatic dark theme for readers whose
//   system prefers dark (the tokens only define [data-theme="dark"]).
// - bundle.css: copied without the Google Fonts @import (fonts are self-hosted
//   with Fontsource; see src/styles/fonts.css).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const from = 'docs/brief/design-system/';
const to = 'src/styles/';
mkdirSync(to, { recursive: true });
const banner = '/* GENERATED by scripts/sync-design-system.mjs from docs/brief/design-system. Do not edit. */\n';

const tokens = readFileSync(from + 'tokens.css', 'utf8');
const dark = tokens.match(/\[data-theme="dark"\]\s*\{[^}]*\}/);
if (!dark) throw new Error('dark theme block not found in tokens.css');
const auto = dark[0].replace('[data-theme="dark"]', ':root:not([data-theme="light"])');
writeFileSync(
  to + 'tokens.css',
  `${banner}${tokens}\n/* Automatic dark theme */\n:root { color-scheme: light dark; }\n:root[data-theme="light"] { color-scheme: light; }\n:root[data-theme="dark"] { color-scheme: dark; }\n@media (prefers-color-scheme: dark) {\n${auto.replace(/^/gm, '  ')}\n}\n`,
);

const bundle = readFileSync(from + 'bundle.css', 'utf8').replace(/^@import url\([^)]*\);\n?/m, '');
writeFileSync(to + 'bundle.css', banner + bundle);
console.log('design system synced');
